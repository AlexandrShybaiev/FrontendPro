// Дано ціле число (ввести через 'prompt').
// З'ясувати, чи просто воно (простим називається число, більше 1,
// що не має інших дільників, крім 1 і себе).
let N = Number(prompt("Введіть ціле число N:"));
let count = 0;

for (let i = 1; i <= N; i++) {
  if (N % i === 0) {
    count++;
    console.log(i);
  }
}
if (N > 1 && count === 2) {
  console.log(N + " — просте число");
} else {
  console.log(N + " — НЕ просте число");
}
